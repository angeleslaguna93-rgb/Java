package basico;

public class Primitivos{
	
	  public static void main (String [] args) {
		  
		  // Los datos primitivos son tipos numéricos y de caracteres ;
		  
		  byte numByte = 20; // numero punto flotante 
		  short numShort = 200; // numero punto flotante 
		  int numInt = 1000; // numero entero 
		  long  numLong = 1_000_000; // numero entero
		  float  numFloat = 234.6f; // numero punto flotante
		  double numDoub = 234.8484848; // numero  punto flotante 
		  boolean DatoBool = true; // Dato binario 
		  char catChar = 'd'; // Caracter 
		  String cadena = "Hola todos";
		  
		  System.out.println("el numero entero byte es" + numByte);
		  System.out.println("el numero short es" + numShort); 
		  System.out.println("el numero entero long es" + numInt);
		  System.out.println("el numero entero es long es" + numLong);
		  System.out.println("el numero de punto flotante float es" + numFloat);
		  System.out.println("el numero de punto flotante double es" + numDoub);
		  System.out.println("el numero del estado boolean es" + DatoBool);
		  System.out.println("el numero de caracter es" + catChar);
		  System.out.println("La cadena es" + cadena);
		  
}
	  
	  
	  
	  
}